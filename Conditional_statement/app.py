score = int(input("Enter your score:"))

if score >= 80:
    print("Excellent Result, I am proud of you")
elif score >= 60:
    print("Good Result, Keep it up")
elif score >= 40:
    print("Average Result, You can do better")
elif score >= 20:
    print("Poor Result, You need to work harder")
else:
    print("Fail, You need to try harder")

